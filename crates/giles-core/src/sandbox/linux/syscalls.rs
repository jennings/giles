//! Docker's default seccomp allowlist for this architecture: generated, don't edit by hand.
//!
//! Source: `seccomp/default.json` in <https://github.com/moby/profiles> at commit
//! `6fe7deb1b9fb7c0397a4593480d7d22b9ee8caef` (2026-09-17, "seccomp: Disable AF_AX25 socket
//! domain"). Selected, as for an unprivileged container on this architecture: the names of every
//! `SCMP_ACT_ALLOW` entry without `args` conditions, without an `includes.caps` (capabilities
//! the plugin never has) or `includes.minKernel` condition, and whose `includes.arches`, if any,
//! names this architecture; then only the names that are syscalls here. Docker's conditional
//! entries (`socket`, `personality`, `clone`) and `minKernel` entry (`ptrace`,
//! `process_vm_readv`, `process_vm_writev`) are handled in `seccomp.rs` instead.
//!
//! The table is Docker's list unchanged, but `seccomp.rs` denies some of it (`DENIED`): System V
//! IPC (`shm*`, `msg*`, `sem*`) and POSIX message queues (`mq_*`), which Docker can allow because
//! every container has its own IPC namespace. The sandbox uses no namespaces, so they'd reach the
//! segments, queues, and semaphores of every process of the same user.
//!
//! Numbers are `libc`'s `SYS_*` constants; the few `libc` doesn't define yet are written out
//! from the kernel's syscall table (Linux 6.12, plus the `*xattrat` calls of 6.13). See
//! "Linux: seccomp" in `Docs/technical/sandbox.md` for how to regenerate it.

